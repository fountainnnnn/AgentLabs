"""Export utilities for agent configurations, reports, and run data."""

import json
import os
import zipfile
from pathlib import Path
from typing import Any

from config import settings
from core.artifact_store import save_artifact, save_json_artifact


def export_json(filename: str, data: object) -> str:
    """Export *data* as a JSON file into the configured export directory.

    Returns the absolute path of the written file.
    """
    base = Path(settings.export_dir)
    base.mkdir(parents=True, exist_ok=True)
    path = base / filename
    with open(path, "w") as fh:
        json.dump(data, fh, indent=2, default=str)
    return str(path.resolve())


def export_zip(run_id: str, files_dict: dict[str, object]) -> str:
    """Export a collection of named JSON objects as a ZIP archive.

    *files_dict* maps filenames (e.g. ``"agent.json"``) to serialisable
    Python objects.  Each value is written to a temp JSON file that is then
    bundled into a ZIP.

    Returns the absolute path of the created ZIP file.
    """
    base = Path(settings.export_dir) / run_id
    base.mkdir(parents=True, exist_ok=True)

    zip_path = base / "export.zip"
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as zf:
        for name, obj in files_dict.items():
            content = json.dumps(obj, indent=2, default=str)
            zf.writestr(name, content)
    return str(zip_path.resolve())


def build_agent_json(
    agent_config: dict[str, Any],
    metrics: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """Build a structured agent export dict from a configuration and metrics."""
    return {
        "agent": agent_config,
        "metrics": metrics or {},
        "export_timestamp": __import__("datetime").datetime.now(
            __import__("datetime").timezone.utc
        ).isoformat(),
    }


def build_report_json(run_data: dict[str, Any]) -> dict[str, Any]:
    """Build a structured hardening report dict from run data."""
    waves = run_data.get("waves", [])
    total_attacks = sum(w.get("total_attacks", 0) for w in waves)
    total_passes = sum(w.get("passes", 0) for w in waves)
    total_fails = sum(w.get("fails", 0) for w in waves)
    total = total_passes + total_fails or 1

    pre_fails = sum(
        sum(1 for r in w.get("pre_patch_results", []) if not r.get("passed"))
        for w in waves
    )
    post_results = [
        r for w in waves
        for r in w.get("post_patch_results") or []
    ]
    post_fails = sum(1 for r in post_results if not r.get("passed"))

    return {
        "run_id": run_data.get("run_id"),
        "target_agent": run_data.get("target_agent_name", run_data.get("target_agent", "")),
        "mode": run_data.get("mode", "mock"),
        "summary": {
            "total_waves": len(waves),
            "total_attacks": total_attacks,
            "total_passes": total_passes,
            "total_fails": total_fails,
            "pass_rate": round(total_passes / total * 100, 1),
            "pre_patch_fail_rate": round(pre_fails / max(total_attacks, 1) * 100, 1),
            "post_patch_fail_rate": round(post_fails / max(len(post_results), 1) * 100, 1),
        },
        "waves": waves,
        "patches": run_data.get("patches", []),
        "export_timestamp": __import__("datetime").datetime.now(
            __import__("datetime").timezone.utc
        ).isoformat(),
    }


def build_runner_py(agent_config: dict[str, Any]) -> str:
    """Generate a standalone Python runner script for an agent configuration."""
    name = agent_config.get("name", "Agent")
    config_json = json.dumps(agent_config, indent=2)

    return f'''"""
{name} - Hardened Agent Runner
Auto-generated by AgentForge
"""

import json
import sys
from pathlib import Path


class HardenedAgentRunner:
    """Sandboxed runner for a hardened agent configuration."""

    CONFIG = {config_json}

    def __init__(self, config: dict | None = None):
        self.config = config or self.CONFIG
        self.guardrails_enabled = True
        self.safety_violations: list[str] = []

    def process_request(self, prompt: str) -> dict:
        """Process a single user request with safety checks (simulated)."""
        # In a real deployment this would call an LLM with the config's
        # system prompt and tools.  Here we simply return a placeholder.
        return {{
            "prompt": prompt,
            "response": "Processed within policy guidelines.",
            "safety_check": "passed" if self.guardrails_enabled else "bypassed",
            "guardrails_triggered": [],
        }}

    def run_interactive(self) -> None:
        print(f"Hardened Agent: {{self.config.get('name', 'Unknown')}}")
        print("Type 'exit' to quit.")
        while True:
            try:
                prompt = input("\\n> ")
                if prompt.lower() in ("exit", "quit"):
                    break
                result = self.process_request(prompt)
                print(f"Agent: {{result['response']}}")
            except (KeyboardInterrupt, EOFError):
                break


if __name__ == "__main__":
    runner = HardenedAgentRunner()
    runner.run_interactive()
'''


def build_model_card(
    model_config: dict[str, Any],
    checkpoint: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """Build a model card suitable for RL-trained checkpoint export."""
    return {
        "model_name": model_config.get("name", "agentforge-model"),
        "base_model": model_config.get("base_model", "unknown"),
        "type": "rl_hardened",
        "checkpoint": checkpoint or {},
        "adapter_config": model_config.get("adapter_config", {}),
        "training_config": {
            k: v for k, v in model_config.items()
            if k in ("learning_rate", "batch_size", "training_steps", "adapter_rank")
        },
        "description": "RL-hardened agent checkpoint generated by AgentForge.",
        "export_timestamp": __import__("datetime").datetime.now(
            __import__("datetime").timezone.utc
        ).isoformat(),
    }


def build_training_report(
    config: dict[str, Any],
    checkpoints: list[dict[str, Any]],
    metrics: dict[str, Any],
) -> dict[str, Any]:
    """Build a comprehensive RL training report."""
    return {
        "config": config,
        "checkpoints": checkpoints,
        "metrics": metrics,
        "summary": {
            "total_steps": config.get("training_steps", 0),
            "final_loss": metrics.get("final_loss"),
            "best_score": metrics.get("best_score"),
            "total_checkpoints": len(checkpoints),
        },
        "export_timestamp": __import__("datetime").datetime.now(
            __import__("datetime").timezone.utc
        ).isoformat(),
    }
